#!/usr/bin/env bash
# Points the iOS project at one country: writes Config/Country.xcconfig and the country's app icon, from the same
# app/countries/<country>/config.json the Android app uses.
#
#   ./configure.sh [country]        (default: the country of app/countries/default.json)
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
COUNTRIES="$ROOT/app/countries"

COUNTRY="${1:-$(node -p "require('$COUNTRIES/default.json').country")}"
CONFIG="$COUNTRIES/$COUNTRY/config.json"
if [ ! -f "$CONFIG" ]; then
	echo "Unknown country: $COUNTRY" >&2
	exit 1
fi

field() { node -p "require('$CONFIG').$1"; }
VERSION="$(node -p "require('$ROOT/android/version.json').version")"
# Same number as the Android versionCode: major * 10000 + minor * 100 + patch.
BUILD="$(node -p "const [a,b,c]='$VERSION'.split('.').map(Number); a*10000+b*100+c")"
color() { field "colors.$1" | tr -d '#'; }

cat > "$HERE/Config/Country.xcconfig" <<XCCONFIG
// Generated by configure.sh for "$COUNTRY". Do not edit, do not commit.
TNT_BUNDLE_ID = $(field applicationId)
TNT_APP_NAME = $(field appName)
// "//" starts a comment in an xcconfig, so the one of the scheme is spelled around it.
TNT_API_URL = $(field apiUrl | sed 's#//#/$()/#')
TNT_COLOR_LIGHTEST = $(color lightest)
TNT_COLOR_LIGHT = $(color light)
TNT_COLOR_MAIN = $(color main)
TNT_COLOR_DARK = $(color dark)
TNT_COLOR_DARKEST = $(color darkest)
TNT_APP_ICON = CountryAppIcon
TNT_VERSION = $VERSION
TNT_BUILD = $BUILD
XCCONFIG

# The country's icon is the favicon of its dashboard (the Android icons are too small for iOS). Without one, or
# if it cannot be rendered, the generic TnT icon is used.
ICONSET="$HERE/Config/Generated/Assets.xcassets/CountryAppIcon.appiconset"
FAVICON="$ROOT/client/countries/$COUNTRY/public/favicon.svg"
rm -rf "$ICONSET"
mkdir -p "$ICONSET"
# iOS rejects icons with transparency.
if [ -f "$FAVICON" ] && magick -background white -density 600 "$FAVICON" -resize 1024x1024 -flatten -alpha off "$ICONSET/icon.png" 2>/dev/null; then
	:
else
	echo "No usable favicon for $COUNTRY, using the generic icon" >&2
	cp "$HERE/TnT/Assets.xcassets/AppIcon.appiconset/icon.png" "$ICONSET/icon.png"
fi
cp "$HERE/TnT/Assets.xcassets/AppIcon.appiconset/Contents.json" "$ICONSET/Contents.json"

echo "Configured iOS for $COUNTRY $VERSION ($BUILD)"
